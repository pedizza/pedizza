create function private.handle_new_user() returns trigger language plpgsql security definer set search_path='' as $$ declare t uuid; store_name text; begin
 insert into public.profiles(id,name) values(new.id,left(coalesce(nullif(trim(new.raw_user_meta_data->>'name'),''),'Usuário'),120));
 store_name=trim(new.raw_user_meta_data->>'store_name');
 if store_name is not null and length(store_name) between 2 and 120 then
  insert into public.tenants(name,slug) values(store_name,'loja-'||replace(gen_random_uuid()::text,'-','')) returning id into t;
  insert into public.tenant_members(tenant_id,user_id,role) values(t,new.id,'owner');
  insert into public.subscriptions(tenant_id,plan_id) select t,id from public.subscription_plans where code='pedizza_monthly';
 end if;
 return new;
end $$;
create trigger pedizza_on_auth_user_created after insert on auth.users for each row execute function private.handle_new_user();
