create table public.tenants (id uuid primary key default gen_random_uuid(), name text not null check(length(name) between 2 and 120), slug text not null unique, manually_suspended boolean not null default false, suspension_reason text, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table public.profiles (id uuid primary key references auth.users(id) on delete cascade, name text not null check(length(name) between 1 and 120), phone text, avatar_url text, blocked boolean not null default false, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table public.tenant_members (id uuid primary key default gen_random_uuid(), tenant_id uuid not null references public.tenants(id), user_id uuid not null references public.profiles(id), role text not null check(role in ('owner','admin','manager','attendant','kitchen','custom')), active boolean not null default true, created_at timestamptz not null default now(), unique(tenant_id,user_id), unique(tenant_id,id));
create table public.permissions (code text primary key, description text not null);
create table public.role_permissions (role text not null, permission text not null references public.permissions(code), primary key(role,permission));
create table public.member_permissions (tenant_id uuid not null, member_id uuid not null, permission text not null references public.permissions(code), allowed boolean not null, primary key(member_id,permission), foreign key(tenant_id,member_id) references public.tenant_members(tenant_id,id));
create table private.super_admins (user_id uuid primary key references public.profiles(id));
create table public.subscription_plans (id uuid primary key default gen_random_uuid(), code text not null unique, name text not null, price_cents integer not null check(price_cents>=0), billing_interval text not null default 'monthly', active boolean not null default true);
