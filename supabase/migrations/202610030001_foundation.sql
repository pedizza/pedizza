create table public.subscriptions (id uuid primary key default gen_random_uuid(), tenant_id uuid not null unique references public.tenants(id), plan_id uuid not null references public.subscription_plans(id), status text not null default 'pending' check(status in ('pending','active','past_due','suspended','cancelled')), provider_subscription_id text unique, current_period_end timestamptz, provider_updated_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now());
create table public.audit_logs (id uuid primary key default gen_random_uuid(), tenant_id uuid references public.tenants(id), user_id uuid references public.profiles(id), action text not null, resource_type text not null, resource_id uuid, metadata jsonb not null default '{}', ip_address inet, user_agent text, created_at timestamptz not null default now());
create function private.member_of(t uuid) returns boolean language sql stable security definer set search_path='' as $$ select exists(select 1 from public.tenant_members m join public.profiles p on p.id=m.user_id where m.tenant_id=t and m.user_id=(select auth.uid()) and m.active and not p.blocked) $$;
create function private.has_permission(t uuid, p text) returns boolean language sql stable security definer set search_path='' as $$
select exists(select 1 from public.tenant_members m join public.profiles u on u.id=m.user_id where m.tenant_id=t and m.user_id=(select auth.uid()) and m.active and not u.blocked and exists(select 1 from public.permissions where code=p) and (m.role='owner' or coalesce((select allowed from public.member_permissions where member_id=m.id and permission=p),exists(select 1 from public.role_permissions where role=m.role and permission=p)))) $$;
create function private.subscription_active(t uuid) returns boolean language sql stable security definer set search_path='' as $$ select exists(select 1 from public.subscriptions s join public.tenants t1 on t1.id=s.tenant_id where s.tenant_id=t and s.status='active' and s.current_period_end>now() and not t1.manually_suspended) $$;
create function public.has_permission(tenant uuid, permission text) returns boolean language sql stable security invoker set search_path='' as $$ select private.has_permission(tenant,permission) $$;
create function public.is_super_admin() returns boolean language sql stable security definer set search_path='' as $$ select exists(select 1 from private.super_admins s join public.profiles p on p.id=s.user_id where s.user_id=(select auth.uid()) and not p.blocked) $$;
revoke all on all functions in schema private from public;
grant usage on schema private to authenticated;
grant execute on function private.member_of(uuid),private.has_permission(uuid,text),private.subscription_active(uuid) to authenticated;
